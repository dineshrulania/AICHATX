import projectModel from '../models/project.model.js';
import * as projectService from '../services/project.service.js';
import userModel from '../models/user.model.js';
import messageModel from '../models/message.model.js';
import { validationResult } from 'express-validator';


export const createProject = async (req, res) => {

    const errors = validationResult(req);

    if (!errors.isEmpty()) {
        return res.status(400).json({ errors: errors.array() });
    }

    try {

        const { name } = req.body;
        const loggedInUser = await userModel.findOne({ email: req.user.email });
        const userId = loggedInUser._id;

        const newProject = await projectService.createProject({ name, userId });

        res.status(201).json(newProject);

    } catch (err) {
        console.log(err);
        res.status(400).send(err.message);
    }



}

export const getAllProject = async (req, res) => {
    try {

        const loggedInUser = await userModel.findOne({
            email: req.user.email
        })

        const allUserProjects = await projectService.getAllProjectByUserId({
            userId: loggedInUser._id
        })

        return res.status(200).json({
            projects: allUserProjects
        })

    } catch (err) {
        console.log(err)
        res.status(400).json({ error: err.message })
    }
}

export const addUserToProject = async (req, res) => {
    const errors = validationResult(req);

    if (!errors.isEmpty()) {
        return res.status(400).json({ errors: errors.array() });
    }

    try {

        const { projectId, users } = req.body

        const loggedInUser = await userModel.findOne({
            email: req.user.email
        })


        const project = await projectService.addUsersToProject({
            projectId,
            users,
            userId: loggedInUser._id
        })

        return res.status(200).json({
            project,
        })

    } catch (err) {
        console.log(err)
        res.status(400).json({ error: err.message })
    }


}

export const getProjectById = async (req, res) => {

    const { projectId } = req.params;

    try {

        const project = await projectService.getProjectById({ projectId });
        if (!project) {
            return res.status(404).json({ error: 'Project not found' });
        }

        const loggedInUser = await userModel.findOne({ email: req.user.email });

        let joinedAtDate = new Date(0); // fallback to start of time
        if (loggedInUser) {
            const uStr = loggedInUser._id.toString();
            if (project.userJoinedAt && project.userJoinedAt.has(uStr)) {
                joinedAtDate = project.userJoinedAt.get(uStr);
            }
        }

        const messages = await messageModel.find({
            project: projectId,
            timestamp: { $gte: joinedAtDate }
        }).sort({ timestamp: 1 });

        return res.status(200).json({
            project,
            messages
        })

    } catch (err) {
        console.log(err)
        res.status(400).json({ error: err.message })
    }

}

